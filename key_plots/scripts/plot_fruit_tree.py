"""Generate fruit_tree_alpha_sweep.tikz directly (no tikzplotlib dependency).

Produces a 2x2 pgfplots groupplot with reinforce/ganesh_mlmc/bai_pg data.
Run from anywhere; uses paths resolved relative to this file.
"""
import json, re
from collections import defaultdict
from pathlib import Path
import numpy as np

LABEL = {"ganesh_mlmc": "MLMC-NPG", "bai_pg": "Policy Gradient",
         "reinforce": "REINFORCE"}

# Tab:purple / tab:blue / tab:red in RGB
COLOR_RGB = {
    "ganesh_mlmc": (148, 103, 189),   # mediumpurple
    "bai_pg":      ( 31, 119, 180),   # steelblue
    "reinforce":   (214,  39,  40),   # crimson/tab:red
}
COLOR_NAME = {k: f"{''.join(str(v) for v in rgb)}" for k, rgb in COLOR_RGB.items()}
# e.g. COLOR_NAME["ganesh_mlmc"] = "1481031892"  -- but we want the actual tikz color names
# Use descriptive names matching tikzplotlib convention
TIKZ_COLOR = {
    "ganesh_mlmc": "mediumpurple148103189",
    "bai_pg":      "steelblue31119180",
    "reinforce":   "crimson2143940",
}

ORDER = list(LABEL.keys())

ALPHAS = [("a010", "0.10"), ("a025", "0.25"), ("a050", "0.50"), ("a100", "1.00")]
PANELS = ["(a)", "(b)", "(c)", "(d)"]

RUN_RE = re.compile(
    r"^(?P<algo>ganesh_mlmc|bai_pg|reinforce)"
    r"_fruit_tree_(?P<atag>a\d+)_\S*_seed(?P<seed>\d+)\.json$"
)

HERE = Path(__file__).resolve().parent
DATA = HERE.parent / "data" / "fruit_tree"
OUT  = HERE.parent / "fruit_tree_alpha_sweep.tikz"

N_GRID = 200

def load_runs(atag):
    runs = defaultdict(list)
    for fp in sorted(DATA.iterdir()):
        m = RUN_RE.match(fp.name)
        if not m or m.group("atag") != atag or m.group("algo") not in ORDER:
            continue
        d = json.load(open(fp))
        runs[m.group("algo")].append({
            "f":    np.asarray(d["f"], float),
            "traj": np.asarray(d["trajectories"], int),
        })
    return runs


def interp_runs(runs):
    """Returns (grid, mean, std, n) for each algo in ORDER."""
    out = {}
    for algo in ORDER:
        rs = runs.get(algo, [])
        if not rs:
            continue
        t_lo = max(r["traj"][0]  for r in rs)
        t_hi = min(r["traj"][-1] for r in rs)
        grid   = np.linspace(t_lo, t_hi, N_GRID)
        curves = np.stack([np.interp(grid, r["traj"], r["f"]) for r in rs])
        mean   = curves.mean(axis=0)
        std    = curves.std(axis=0, ddof=1)
        out[algo] = (grid, mean, std, len(rs))
    return out


def band_path(grid, mean, std, color):
    r"""Generate \path [...] --cycle; block for confidence band."""
    upper = mean + std
    lower = mean - std
    lines = [f"\\path [draw={color}, fill={color}, opacity=0.18]"]
    # forward along upper
    lines.append(f"(axis cs:{grid[0]:.6g},{upper[0]:.6g})")
    for x, y in zip(grid[1:], upper[1:]):
        lines.append(f"--(axis cs:{x:.6g},{y:.6g})")
    # backward along lower
    for x, y in zip(grid[::-1], lower[::-1]):
        lines.append(f"--(axis cs:{x:.6g},{y:.6g})")
    lines.append("--cycle;")
    return "\n".join(lines)


def mean_line(grid, mean, color):
    """Generate \addplot [...] table {%...}; block for mean line."""
    lines = [f"\\addplot [line width=0.68pt, {color}]",
             "table {%"]
    for x, y in zip(grid, mean):
        lines.append(f"{x:.6g} {y:.6g}")
    lines.append("};")
    return "\n".join(lines)


def fmt_yrange(data_dict):
    lo = min((m - s).min() for (_, m, s, _) in data_dict.values())
    hi = max((m + s).max() for (_, m, s, _) in data_dict.values())
    pad = (hi - lo) * 0.05
    return lo - pad, hi + pad


# ── header ─────────────────────────────────────────────────────────────────
header = r"""% Generated by plot_fruit_tree.py
\begin{tikzpicture}

\definecolor{crimson2143940}{RGB}{214,39,40}
\definecolor{darkgray176}{RGB}{176,176,176}
\definecolor{lightgray204}{RGB}{204,204,204}
\definecolor{mediumpurple148103189}{RGB}{148,103,189}
\definecolor{steelblue31119180}{RGB}{31,119,180}

\begin{groupplot}[group style={group size=2 by 2, horizontal sep=1.5cm, vertical sep=2.2cm}]
"""

footer = r"""\end{groupplot}
\node[anchor=north] at ([yshift=-0.3cm]current bounding box.south)
  {\pgfplotslegendfromname{sharedlegend}};
\end{tikzpicture}
"""

blocks = [header]

for subplot_idx, ((atag, alpha), panel) in enumerate(zip(ALPHAS, PANELS)):
    is_first = (subplot_idx == 0)
    is_left  = (subplot_idx % 2 == 0)

    runs = load_runs(atag)
    data = interp_runs(runs)

    if not data:
        print(f"WARNING: no data for {atag}")
        continue

    ylo, yhi = fmt_yrange(data)
    xlo = min(d[0][0]  for d in data.values())
    xhi = max(d[0][-1] for d in data.values())
    xpad = (xhi - xlo) * 0.05

    # ── \nextgroupplot options ───────────────────────────────────────────
    opt_lines = ["\\nextgroupplot[",
                 "height=6cm,"]

    if is_first:
        opt_lines += [
            "legend cell align={left},",
            "legend style={",
            "  font=\\footnotesize,",
            "  /tikz/every even column/.append style={column sep=5pt},",
            "},",
            "legend to name=sharedlegend,",
            "legend columns=3,",
        ]
    else:
        opt_lines.append("legend style={opacity=0, at={(0,0)}, overlay},")

    opt_lines += [
        "tick align=outside,",
        "tick pos=left,",
        f"title={{\\textbf{{{panel}}} $\\alpha = {alpha}$}},",
        "width=7cm,",
        "xlabel={Sampled Trajectories},",
        f"xmin={xlo - xpad:.6g}, xmax={xhi + xpad:.6g},",
        "xtick={0,4000,8000,12000},",
        "scaled x ticks=false,",
        "xtick style={color=black},",
    ]

    opt_lines.append(r"ylabel={Fruit Tree: $f_\alpha(J^\pi)$},")

    opt_lines += [
        f"ymin={ylo:.10g}, ymax={yhi:.10g},",
        "ytick style={color=black}",
        "]",
    ]

    blocks.append("\n".join(opt_lines))

    # ── plot data (bands then lines, then legend entries) ───────────────
    for algo in ORDER:
        if algo not in data:
            continue
        grid, mean, std, n = data[algo]
        color = TIKZ_COLOR[algo]
        blocks.append(band_path(grid, mean, std, color))

    for algo in ORDER:
        if algo not in data:
            continue
        grid, mean, std, n = data[algo]
        color = TIKZ_COLOR[algo]
        blocks.append(mean_line(grid, mean, color))
        if is_first:
            blocks.append(f"\\addlegendentry{{{LABEL[algo]}}}")

    blocks.append("")   # blank line between subplots

blocks.append(footer)

OUT.write_text("\n".join(blocks), encoding="utf-8")
print(f"wrote {OUT}")

# ── Companion PNG via matplotlib ───────────────────────────────────────────
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

PNG_COLOR = {"ganesh_mlmc": "tab:purple", "bai_pg": "tab:blue", "reinforce": "tab:red"}
PNG_OUT   = HERE.parent / "fruit_tree_alpha_sweep.png"

fig, axes = plt.subplots(2, 2, figsize=(14, 10))
axes_flat = axes.flatten()
for idx, ((atag, alpha), panel) in enumerate(zip(ALPHAS, PANELS)):
    runs = load_runs(atag)
    data = interp_runs(runs)
    ax = axes_flat[idx]
    for algo in ORDER:
        if algo not in data:
            continue
        grid, mean, std, n = data[algo]
        ax.plot(grid, mean, color=PNG_COLOR[algo], lw=1.7,
                label=f"{LABEL[algo]} (n={n})")
        ax.fill_between(grid, mean - std, mean + std,
                        color=PNG_COLOR[algo], alpha=0.18)
    ax.set_title(rf"$({chr(ord('a')+idx)})$  $\alpha = {alpha}$")
    ax.set_xlabel("Sampled Trajectories")
    if idx % 2 == 0:
        ax.set_ylabel(r"Fruit Tree: $f_\alpha(J^\pi)$")
    if idx == 0:
        ax.legend(fontsize=9, loc="lower right")
fig.tight_layout()
fig.savefig(PNG_OUT, dpi=150, bbox_inches="tight")
plt.close(fig)
print(f"wrote {PNG_OUT}")
